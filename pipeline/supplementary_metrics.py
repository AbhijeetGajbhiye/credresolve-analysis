def canon_calls_attempts(calls, attempts, disp):
    calls = calls.sort_values(["call_id", "event_at"]).drop_duplicates("call_id", keep="first").copy()
    attempts = attempts.sort_values(["attempt_id", "event_at"]).drop_duplicates("attempt_id", keep="first").copy()
    attempts = attempts.merge(calls[["call_id", "call_status"]], on="call_id", how="left")
    disp = disp.sort_values(["call_id", "event_at"]).drop_duplicates(["call_id", "disposition_code"], keep="first").copy()
    valid_answered = set(calls.loc[calls.call_status.eq("ANSWERED"), "call_id"])
    disp = disp[disp.call_id.isin(valid_answered)].copy()
    calls["month"] = calls.event_at.dt.to_period("M").astype(str)
    attempts["month"] = attempts.event_at.dt.to_period("M").astype(str)
    disp["month"] = disp.event_at.dt.to_period("M").astype(str)
    return calls, attempts, disp


