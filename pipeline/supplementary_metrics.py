def next_payment_window_flags(rows: pd.DataFrame, payments: pd.DataFrame, date_col: str, window_days: int) -> tuple[pd.Series, pd.Series]:
    """Return payer flag and next-payment amount using per-account binary search."""
    out_flag = pd.Series(False, index=rows.index)
    out_amt = pd.Series(0.0, index=rows.index)
    pay_groups = {k: g.sort_values('event_at') for k, g in payments.groupby('account_id')}
    for acct, grp in rows.groupby('account_id', sort=False):
        pg = pay_groups.get(acct)
        if pg is None or pg.empty:
            continue
        ptime = pg.event_at.to_numpy(dtype='datetime64[ns]')
        pamt = pg.amount.to_numpy(dtype=float)
        for row_idx, date_value in zip(grp.index, grp[date_col]):
            pos = np.searchsorted(ptime, np.datetime64(date_value) + np.timedelta64(1, 'D'), side='left')
            if pos < len(ptime) and ptime[pos] < np.datetime64(date_value) + np.timedelta64(window_days + 1, 'D'):
                out_flag.at[row_idx] = True
                out_amt.at[row_idx] = pamt[pos]
    return out_flag, out_amt


def last_touch_before_payment(payments: pd.DataFrame, interactions: pd.DataFrame) -> pd.DataFrame:
    """Find latest interaction strictly before each payment using per-account binary search."""
    int_groups = {k: g.sort_values('event_at') for k, g in interactions.groupby('account_id')}
    out = payments[['payment_id','account_id','event_at','amount']].copy()
    out['last_touch_event_at'] = pd.NaT
    out['last_touch_channel'] = None
    for acct, grp in out.groupby('account_id', sort=False):
        ig = int_groups.get(acct)
        if ig is None or ig.empty:
            continue
        it = ig.event_at.to_numpy(dtype='datetime64[ns]')
        for row_idx, pay_time in zip(grp.index, grp.event_at):
            pos = np.searchsorted(it, np.datetime64(pay_time), side='left') - 1
            if pos >= 0:
                out.at[row_idx, 'last_touch_event_at'] = ig.iloc[pos].event_at
                out.at[row_idx, 'last_touch_channel'] = ig.iloc[pos].channel
    return out

