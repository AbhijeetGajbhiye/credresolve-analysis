    build_denominator(results,pay,targets,accounts)
    build_confidence(results)
    build_summary(results,annual_ops,avg_targeted_payer,break_even_pp,lift)
    write_manifest(results)
    print(f'Supplementary metrics complete: {len(json.loads((results/"rebuild_manifest.json").read_text())["generated_files"])} outputs regenerated.', flush=True)


